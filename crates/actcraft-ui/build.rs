//! Embeds every language file in `i18n/`: `i18n/<code>.tsv` (craft-i18n catalog format) becomes a
//! language the window offers, with no code change. English is the source text and has no file.
//!
//! Writes `$OUT_DIR/languages.rs` with `CATALOGS` (for `craft_i18n::I18n::new`) and `OFFERED`.

use std::fmt::Write as _;
use std::path::Path;

/// A language code craft-i18n accepts as a file name: lower-case letters, digits and `-`.
fn valid_code(code: &str) -> bool {
    !code.is_empty()
        && code != "en"
        && code != "pseudo"
        && code.len() <= 16
        && code.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && code.bytes().next().is_some_and(|b| b.is_ascii_lowercase())
}

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("i18n");
    println!("cargo::rerun-if-changed={}", dir.display());
    let mut codes: Vec<String> = Vec::new();
    if let Ok(entries) = std::fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("tsv") {
                continue;
            }
            let Some(code) = path.file_stem().and_then(|s| s.to_str()).map(str::to_owned) else {
                continue;
            };
            if valid_code(&code) {
                println!("cargo::rerun-if-changed={}", path.display());
                codes.push(code);
            } else {
                println!(
                    "cargo::warning=i18n/{code}.tsv skipped: the file name must be a language code such as de or pt-br"
                );
            }
        }
    }
    codes.sort();
    let mut out = String::from("// Generated by actcraft-ui's build.rs from i18n/*.tsv. Do not edit.\n");
    out.push_str("static CATALOGS: &craft_i18n::Embedded = &[\n");
    for code in &codes {
        let _ = writeln!(
            out,
            "    ({code:?}, \"\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/i18n/{code}.tsv\"))),"
        );
    }
    out.push_str("];\n");
    let _ = writeln!(out, "const OFFERED: &[&str] = &{codes:?};");
    let target = Path::new(&std::env::var("OUT_DIR").unwrap_or_default()).join("languages.rs");
    if let Err(e) = std::fs::write(&target, out) {
        println!("cargo::error=could not write {}: {e}", target.display());
    }
    help();
}

/// Embeds the help: `i18n/help/<language>/<page>.md` (English in `en/`), the pictures in
/// `i18n/help/img_<language>/<name>.png`, and the page order in `i18n/help/contents.txt`.
/// Writes `$OUT_DIR/help.rs` with `HELP_PAGES` (language, page, text), `HELP_IMAGES` (language,
/// name, PNG bytes) and `HELP_ORDER`.
fn help() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("i18n").join("help");
    println!("cargo::rerun-if-changed={}", dir.display());
    let mut pages = Vec::new();
    let mut images = Vec::new();
    let mut folders: Vec<String> = std::fs::read_dir(&dir)
        .map(|r| r.flatten().filter(|e| e.path().is_dir()).filter_map(|e| e.file_name().into_string().ok()).collect())
        .unwrap_or_default();
    folders.sort();
    for folder in folders {
        let (lang, pictures) = match folder.strip_prefix("img_") {
            Some(lang) => (lang.to_owned(), true),
            None => (folder.clone(), false),
        };
        if lang != "en" && !valid_code(&lang) {
            println!("cargo::warning=i18n/help/{folder} skipped: the name must be a language code");
            continue;
        }
        let want = if pictures { "png" } else { "md" };
        let mut files: Vec<String> = std::fs::read_dir(dir.join(&folder))
            .map(|r| r.flatten().filter_map(|e| e.file_name().into_string().ok()).collect())
            .unwrap_or_default();
        files.sort();
        for file in files {
            let Some(name) = file.strip_suffix(&format!(".{want}")) else { continue };
            let valid = !name.is_empty()
                && name.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-' || b == b'_');
            if !valid {
                println!("cargo::warning=i18n/help/{folder}/{file} skipped: use lower-case letters, digits, - and _");
                continue;
            }
            let path = format!("/i18n/help/{folder}/{file}");
            println!("cargo::rerun-if-changed={}", dir.join(&folder).join(&file).display());
            if pictures {
                images.push((lang.clone(), name.to_owned(), path));
            } else {
                pages.push((lang.clone(), name.to_owned(), path));
            }
        }
    }
    let order_file = dir.join("contents.txt");
    println!("cargo::rerun-if-changed={}", order_file.display());
    let order: Vec<String> = std::fs::read_to_string(&order_file)
        .unwrap_or_default()
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(str::to_owned)
        .collect();
    let mut out = String::from("// Generated by actcraft-ui's build.rs from i18n/help. Do not edit.\n");
    out.push_str("static HELP_PAGES: &[(&str, &str, &str)] = &[\n");
    for (lang, name, path) in &pages {
        let _ =
            writeln!(out, "    ({lang:?}, {name:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {path:?}))),");
    }
    out.push_str("];\nstatic HELP_IMAGES: &[(&str, &str, &[u8])] = &[\n");
    for (lang, name, path) in &images {
        let _ =
            writeln!(out, "    ({lang:?}, {name:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {path:?}))),");
    }
    out.push_str("];\n");
    let _ = writeln!(out, "static HELP_ORDER: &[&str] = &{order:?};");
    let target = Path::new(&std::env::var("OUT_DIR").unwrap_or_default()).join("help.rs");
    if let Err(e) = std::fs::write(&target, out) {
        println!("cargo::error=could not write {}: {e}", target.display());
    }
}
