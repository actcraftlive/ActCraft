//! Embeds every language file in `i18n/`: `i18n/<code>.tsv` (craft-i18n catalog format) becomes a
//! language the window offers, with no code change. English is the source text and has no file.
//!
//! Writes `$OUT_DIR/languages.rs` with `CATALOGS` (for `craft_i18n::I18n::new`) and `OFFERED`.

use std::fmt::Write as _;
use std::path::Path;

/// A language code craft-i18n accepts as a file name: lower-case letters, digits and `-`.
fn valid_code(code: &str) -> bool {
    !code.is_empty()
        && code != "en"
        && code != "pseudo"
        && code.len() <= 16
        && code.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && code.bytes().next().is_some_and(|b| b.is_ascii_lowercase())
}

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("i18n");
    println!("cargo::rerun-if-changed={}", dir.display());
    let mut codes: Vec<String> = Vec::new();
    if let Ok(entries) = std::fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("tsv") {
                continue;
            }
            let Some(code) = path.file_stem().and_then(|s| s.to_str()).map(str::to_owned) else {
                continue;
            };
            if valid_code(&code) {
                println!("cargo::rerun-if-changed={}", path.display());
                codes.push(code);
            } else {
                println!(
                    "cargo::warning=i18n/{code}.tsv skipped: the file name must be a language code such as de or pt-br"
                );
            }
        }
    }
    codes.sort();
    let mut out = String::from("// Generated by actcraft-ui's build.rs from i18n/*.tsv. Do not edit.\n");
    out.push_str("static CATALOGS: &craft_i18n::Embedded = &[\n");
    for code in &codes {
        let _ = writeln!(
            out,
            "    ({code:?}, \"\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/i18n/{code}.tsv\"))),"
        );
    }
    out.push_str("];\n");
    let _ = writeln!(out, "const OFFERED: &[&str] = &{codes:?};");
    let target = Path::new(&std::env::var("OUT_DIR").unwrap_or_default()).join("languages.rs");
    if let Err(e) = std::fs::write(&target, out) {
        println!("cargo::error=could not write {}: {e}", target.display());
    }
}
